// Builds src/tokens/tokens.css from the three token layers in /tokens.
//   primitives.json  -> raw values            (--dk-color-indigo-600)
//   semantic.json    -> meaning, per theme    (--dk-color-action-primary)
//   components.json  -> per-component tokens  (--dk-button-primary-bg)
// References like {color.indigo.600} become var(--dk-color-indigo-600), so a theme
// switch only swaps the semantic layer and everything downstream follows.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (f) => JSON.parse(readFileSync(join(root, 'tokens', f), 'utf8'));
const PREFIX = 'dk';

const toVar = (path) => `--${PREFIX}-${path.join('-')}`;

function flatten(obj, path = [], out = []) {
  for (const [key, value] of Object.entries(obj)) {
    if (key.startsWith('$')) continue;
    if (value && typeof value === 'object') flatten(value, [...path, key], out);
    else out.push([path.concat(key), String(value)]);
  }
  return out;
}

function resolveRefs(value, known) {
  return value.replace(/\{([^}]+)\}/g, (_, ref) => {
    const name = toVar(ref.split('.'));
    if (!known.has(name)) throw new Error(`Unknown token reference {${ref}} in "${value}"`);
    return `var(${name})`;
  });
}

const primitives = flatten(read('primitives.json'));
const semantic = read('semantic.json');
const components = flatten(read('components.json'));

const known = new Set(primitives.map(([p]) => toVar(p)));
const lightSem = flatten(semantic.light);
const darkSem = flatten(semantic.dark);

// Both themes must define exactly the same semantic tokens.
const names = (list) => list.map(([p]) => toVar(p)).sort().join('|');
if (names(lightSem) !== names(darkSem)) throw new Error('Light and dark semantic tokens do not match');
lightSem.forEach(([p]) => known.add(toVar(p)));

components.forEach(([p]) => known.add(toVar(p)));
const block = (list) => list.map(([p, v]) => `  ${toVar(p)}: ${resolveRefs(v, known)};`).join('\n');

const css = `/* Generated by scripts/build-tokens.mjs. Do not edit by hand. */

:root {
${block(primitives)}
}

:root,
[data-theme='light'] {
  color-scheme: light;
${block(lightSem)}
}

[data-theme='dark'] {
  color-scheme: dark;
${block(darkSem)}
}

/* Component tokens are re-declared on every themed element, not only :root.
   A custom property's var() resolves where it is declared, so declaring these
   on :root alone would freeze them to the light theme inside a dark subtree. */
:root,
[data-theme] {
${block(components)}
}
`;

const outDir = join(root, 'src', 'tokens');
mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, 'tokens.css'), css);
console.log(
  `tokens.css: ${primitives.length} primitive, ${lightSem.length} semantic (x2 themes), ${components.length} component tokens`,
);
